# -*- coding: utf-8 -*-
"""front_copy.py - the rotating copy on the front page.

WHY THIS EXISTS
The front page is generated by `build_cards.py`, so anything written into
`index.html` is overwritten by the next build. That was discovered the hard way:
a whole masthead redesign and ten rewritten teasers were applied to the output
file, the gate chain ran `build_cards`, and **every one of them was silently
reverted** - the page went back to its old self with the gates green. A tool
that rotates the copy in the *output* is a tool that rotates nothing.

So the copy lives in `data/front_copy.json`, one edition per bi-daily release,
and the generator reads it. This tool moves the pointer and captures new
editions; it never edits HTML.

WHAT IT DOES
  --list                 every edition, with its date and note, and which one
                         is live
  --current              print the live edition
  --save [--note "..."]  capture the live edition as a NEW one dated today, as a
                         starting point for edits. Refuses to overwrite a date
                         that already exists, and refuses if the live edition
                         has a slot the file does not know about.
  --stamp <date>         set the live edition. Does not rebuild anything; run
                         build_cards.py afterwards.
  --set <slot> <text> --to <date>
                         write one slot's copy into an edition
  --diff <a> <b>         two editions, side by side

Editions are **appended, never rewritten** - the sequence of what the front page
said is the record. The exception is `--set`, which edits one slot in one named
edition and prints the before and after, because a release is going to want to
change one sentence without re-typing the page.
"""
import json
import pathlib
import sys
from datetime import date

sys.stdout.reconfigure(encoding="utf-8")

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "front_copy.json"

SLOTS = ["kicker", "line", "thesis_word", "thesis_thing", "thesis_pair",
         "clerk_line", "door_stories", "door_encyclopedia"]


def _load():
    if not DATA.exists():
        sys.exit(f"refusing: {DATA} does not exist. Seed it with "
                 f"`python tools/seed_front_copy.py`.")
    d = json.loads(DATA.read_text(encoding="utf-8"))
    if sorted(d) != ["_live", "_note", "editions"]:
        sys.exit(f"refusing: {DATA} top-level keys are {sorted(d)}; expected "
                 f"['_live', '_note', 'editions']")
    return d


def _save(d):
    DATA.write_bytes(json.dumps(d, ensure_ascii=False, indent=2)
                     .replace("\n", "\r\n").encode("utf-8"))


def _live(d):
    ed = next((e for e in d["editions"] if e["date"] == d.get("_live")), None)
    if ed is None:
        sys.exit(f"refusing: _live is {d.get('_live')!r}, which is not an "
                 f"edition in this file")
    return ed


def _flat(ed):
    return {k: ed["copy"].get(k, "") for k in SLOTS}


def main():
    a = sys.argv[1:]
    d = _load()
    ed = _live(d)

    if "--list" in a:
        print(f"  {len(d['editions'])} edition(s), live is "
              f"{d['_live']} ({ed.get('note', '')[:60]})")
        for e in d["editions"]:
            mark = " <- live" if e["date"] == d["_live"] else ""
            print(f"    {e['date']}  {e.get('note', '')[:66]}{mark}")
        return 0

    if "--current" in a:
        print(json.dumps({"date": ed["date"], "note": ed.get("note", ""),
                          "copy": _flat(ed)}, ensure_ascii=False, indent=2))
        return 0

    if "--stamp" in a:
        want = a[a.index("--stamp") + 1]
        if not any(e["date"] == want for e in d["editions"]):
            sys.exit(f"refusing: no edition dated {want}")
        d["_live"] = want
        _save(d)
        print(f"  live edition is now {want} - run "
              f"python tools/build_cards.py to put it on the page")
        return 0

    if "--save" in a:
        note = ""
        if "--note" in a:
            note = a[a.index("--note") + 1]
        today = date.today().isoformat()
        if any(e["date"] == today for e in d["editions"]):
            sys.exit(f"refusing: an edition for {today} already exists. Use "
                     f"--set to edit it, or pick another date.")
        fresh = {"date": today, "note": note, "copy": _flat(ed)}
        d["editions"].append(fresh)
        d["_live"] = today
        _save(d)
        print(f"  copied {ed['date']} to {today} and made it live "
              f"({note or 'no note'})")
        print("  now: python tools/front_copy.py --set <slot> <text> --to "
              f"{today}")
        return 0

    if "--set" in a:
        slot = a[a.index("--set") + 1]
        text = a[a.index("--set") + 2]
        to = a[a.index("--to") + 1] if "--to" in a else d["_live"]
        if slot not in SLOTS:
            sys.exit(f"refusing: unknown slot {slot!r}. Slots: {SLOTS}")
        tgt = next((e for e in d["editions"] if e["date"] == to), None)
        if not tgt:
            sys.exit(f"refusing: no edition dated {to}")
        before = tgt["copy"].get(slot, "")
        if not text.strip():
            sys.exit("refusing: empty copy")
        tgt["copy"][slot] = text
        _save(d)
        print(f"  {to} . {slot}")
        print(f"    - {before}")
        print(f"    + {text}")
        return 0

    if "--diff" in a:
        x, y = a[a.index("--diff") + 1], a[a.index("--diff") + 2]
        ex = next((e for e in d["editions"] if e["date"] == x), None)
        ey = next((e for e in d["editions"] if e["date"] == y), None)
        if not ex or not ey:
            sys.exit(f"refusing: no edition {x} or {y}")
        for k in SLOTS:
            if _flat(ex)[k] != _flat(ey)[k]:
                print(f"  {k}:\n    {x}: {_flat(ex)[k]}\n    {y}: "
                      f"{_flat(ey)[k]}")
        return 0

    print(__doc__)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
