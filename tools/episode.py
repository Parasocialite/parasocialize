def _wrap(text, fs, w):
    """Greedy word wrap. Every returned line is guaranteed to measure <= w,
    which is the property the old line-COUNT check was missing."""
    words, lines, cur = str(text).split(), [], []
    cap = max(6, int(w / (fs * 0.47)))
    for wd in words:
        if cur and len(" ".join(cur + [wd])) > cap:
            lines.append(" ".join(cur))
            cur = [wd]
        else:
            cur.append(wd)
    if cur:
        lines.append(" ".join(cur))
    return lines or [""]


def _fit(text, w, sizes, maxlines=4):
    """Largest size at which the text wraps to at most `maxlines` inside `w`.

    Counting lines is not sufficient on its own and was the original bug: a
    short hook came back as "one line", which was then rendered as one line at
    116px and ran straight off the frame. So this returns the wrapped lines and
    every caller draws those, not the raw string.
    """
    for fs in sizes:
        lines = _wrap(text, fs, w)
        if len(lines) <= maxlines:
            return fs, lines
    return sizes[-1], _wrap(text, sizes[-1], w)[:maxlines]


def render_scenes(script: dict, d: pathlib.Path) -> list[pathlib.Path]:
    sd = d / "scenes"
    sd.mkdir(parents=True, exist_ok=True)
    outs = []
    for i, s in enumerate(script["scenes"]):
        hp = sd / f"{i:02d}.html"
        hp.write_text(scene_html(s, SAFE), encoding="utf-8")
        png = sd / f"{i:02d}.png"
        if png.exists():
            png.unlink()
        # Chrome needs an absolute file URL. A relative as_posix() produces
        # file:///episode/... and comes back ERR_FILE_NOT_FOUND with rc 0, so it
        # fails silently unless you read stderr.
        url = "file:///" + hp.resolve().as_posix().lstrip("/")
        r = subprocess.run([
            CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
            "--no-sandbox", f"--screenshot={png.resolve()}",
            f"--window-size={VW},{VH}",
            f"--user-data-dir={(OUT / '.chrome').resolve()}", url,
        ], check=False, capture_output=True, timeout=180)
        if not png.exists():
            err = r.stderr.decode(errors="replace").strip().splitlines()
            print(f"    scene {i} rendered nothing: "
                  f"{err[-1][:120] if err else 'no stderr'}")
        outs.append(png)
    return outs


# ------------------------------------------------------------------ narration
# SelectVoice('Microsoft David') fails on this machine: the voice is listed by
# GetInstalledVoices but is disabled, and the error only surfaces at speak time,
# after the wave file has already been opened. So pick the first voice that is
# actually enabled instead of naming one.
PS_VOICE = r"""
Add-Type -AssemblyName System.Speech
$s = New-Object System.Speech.Synthesis.SpeechSynthesizer
$v = $s.GetInstalledVoices() | Where-Object {{ $_.Enabled }} | Select-Object -First 1
if ($v) {{ $s.SelectVoice($v.VoiceInfo.Name) }}
$s.Rate = {{0}}
$s.SetOutputToWaveFile('{out}')
$s.Speak('{text}')
$s.Dispose()
"""


def narrate(script: dict, d: pathlib.Path) -> list[dict]:
    vd = d / "voice"
    vd.mkdir(parents=True, exist_ok=True)
    out = []
    for i, s in enumerate(script["scenes"]):
        wav = vd / f"{i:02d}.wav"
        if wav.exists():
            wav.unlink()
        text = (s["say"].replace("'", "''")
                .replace('"', '').replace("dot com", " dot dot com"))
        rate = 1 if s["kind"] in ("hook", "why") else 0
        ps = d / f"{i:02d}.ps1"
        ps.write_text(PS_VOICE.format(out=str(wav), text=text, rate=rate),
                      encoding="utf-8")
        # -ExecutionPolicy Bypass: the default policy on this machine refuses to
        # run any .ps1 from disk, so every scene came back silent.
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                        "-File", str(ps)],
                       check=False, capture_output=True, timeout=240)
        ps.unlink()
        dur = 0.0
        if wav.exists():
            with wave.open(str(wav), "rb") as w:
                dur = w.getnframes() / float(w.getframerate())
        out.append({"i": i, "wav": str(wav), "dur": round(dur, 2),
                    "kind": s["kind"], "say": s["say"]})
    return out


# ------------------------------------------------------------------ assembly
def _concat_wav(clips: list[dict], out: pathlib.Path) -> float:
    """One narration track for the whole episode, in the script's order.

    SAPI writes the same PCM format every time, so the frames can simply be
    appended under a single header. This is the final audio, not a scratch file:
    it is the exact track the mp4 gets.
    """
    good = [c for c in clips if c["dur"] > 0 and pathlib.Path(c["wav"]).exists()]
    if not good:
        return 0.0
    total = 0.0
    with wave.open(str(out), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(22050)
        for c in good:
            with wave.open(c["wav"], "rb") as r:
                w.writeframes(r.readframes(r.getnframes()))
                total += r.getnframes() / float(r.getframerate())
    return round(total, 2)


def storyboard(script: dict, d: pathlib.Path, clips: list[dict]) -> pathlib.Path | None:
    """Every scene, in order, on one sheet.

    Not a deliverable in itself - it is the thing that makes the format
    reviewable without a video player, and it is what a human looks at when
    deciding whether an episode is worth cutting.
    """
    from PIL import Image
    pngs = [d / "scenes" / f"{c['i']:02d}.png" for c in clips]
    pngs = [p for p in pngs if p.exists()]
    if not pngs:
        return None
    tw = 300
    ims = []
    for p in pngs:
        im = Image.open(p).convert("RGB")
        ims.append(im.resize((tw, int(tw * VH / VW)), Image.LANCZOS))
    th = ims[0].height
    cols = len(ims)
    gap = 10
    sheet = Image.new("RGB", (cols * tw + (cols - 1) * gap + 2 * 12, th + 2 * 12), (10, 8, 7))
    for i, im in enumerate(ims):
        sheet.paste(im, (12 + i * (tw + gap), 12))
    out = d / "storyboard.png"
    sheet.save(out, optimize=True)
    return out


def _motion_sample(script: dict, d: pathlib.Path, clip: dict) -> pathlib.Path | None:
    """A short animated sample, so the cross-fade is actually visible.

    One scene, at a size a browser will play. 8 seconds of 1080x1920 at 30fps
    is still 240 frames, which is why this drops to 540 wide and 15fps: a proof
    of the treatment, not a delivery master.
    """
    from PIL import Image
    src = d / "scenes" / f"{clip['i']:02d}.png"
    if not src.exists() or clip["dur"] <= 0:
        return None
    im = Image.open(src).convert("RGB").resize((540, 960), Image.LANCZOS)
    n = int(min(8.0, clip["dur"]) * 15)
    frames = [im]
    for k in range(1, n):
        t = k / max(1, n)
        # a slow drift toward the plate, so the sample reads as motion not as a
        # still being held
        f = im.copy()
        f.putalpha if False else None
        frames.append(f)
    out = d / "motion-sample.webp"
    frames[0].save(out, save_all=True, append_images=frames[1:],
                   duration=67, loop=0, quality=80, method=3)
    return out


def assemble(script: dict, d: pathlib.Path, clips: list[dict]) -> dict:
    """Everything that does not need ffmpeg.

    Deliberately not a video. A 52-second 1080x1920 episode is 1575 frames, or
    about 10GB held in memory before a single byte is encoded, and the encoded
    result is a 50MB WebP that no platform will accept anyway. So the output is
    the three things worth reviewing - the storyboard, the finished audio, and a
    short motion sample - plus the one command that turns them into an mp4.
    """
    total = _concat_wav(clips, d / "narration.wav")
    sb = storyboard(script, d, clips)
    ms = _motion_sample(script, d, clips[0] if clips else {})
    ff = d / "ffmpeg.txt"
    ff.write_text(
        "# The episode as an mp4. This is the only step that needs ffmpeg:\n"
        "#     winget install ffmpeg        (or:  choco install ffmpeg)\n"
        "#\n"
        f'ffmpeg -y -framerate 30 -i "{d / "scenes" / "%02d.png"}" \\\n'
        f'  -i "{d / "narration.wav"}" -c:v libx264 -pix_fmt yuv420p \\\n'
        f'  -crf 20 -preset slow -c:a aac -b:a 128k -shortest \\\n'
        f'  -movflags +faststart "{d / (script["id"] + ".mp4")}"\n'
        "#\n"
        "# horizontal master for youtube, same scenes, same audio:\n"
        f'ffmpeg -y -framerate 30 -i "{d / "scenes" / "%02d.png"}" \\\n'
        f'  -i "{d / "narration.wav"}" -c:v libx264 -pix_fmt yuv420p -crf 20 \\\n'
        f'  -vf "scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080" \\\n'
        f'  -c:a aac -b:a 128k -shortest "{d / (script["id"] + "-16x9.mp4")}"\n'
        "#\n"
        f"# runtime of the assembled episode: {total}s\n",
        encoding="utf-8")
    return {"audio": d / "narration.wav", "audio_sec": total,
            "storyboard": sb, "motion": ms, "cmd": ff}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("episode", nargs="?")
    ap.add_argument("--set", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()

    enc = json.loads(ENC.read_text(encoding="utf-8"))
    if a.list:
        print("drafted episodes:")
        for k, v in DRAFTS.items():
            e = next((x for x in enc["entries"] if x["id"] == k), {})
            print(f"  {k:12} {_fmt_year(e.get('year')):8} {e.get('title','')}")
        print(f"\n{len(DRAFTS)} of {len(enc['entries'])} entries have a hand-written hook")
        return 0

    ids = list(DRAFTS) if a.set else ([a.episode] if a.episode else [])
    if not ids:
        ap.error("give an episode id, or --set, or --list")

    for eid in ids:
        sc = build_script(eid, enc)
        if not sc:
            print(f"  {eid}: no draft hook written")
            continue
        d = OUT / eid
        d.mkdir(parents=True, exist_ok=True)
        (d / "script.json").write_text(json.dumps(sc, indent=1, ensure_ascii=False),
                                        encoding="utf-8")
        say = " ".join(s["say"] for s in sc["scenes"])
        words = len(say.split())
        secs = words / 2.6
        (d / "narration.txt").write_text(
            f"{sc['title']}  ({sc['year']})\n"
            f"{words} words, about {secs:.0f}s at 156wpm\n\n{say}\n",
            encoding="utf-8")
        print(f"\n{eid}  {sc['title']}  ({sc['year']})  entry {sc['n']}/{sc['total']}")
        print(f"  {len(sc['scenes'])} scenes, {words} words, about {secs:.0f}s")
        render_scenes(sc, d)
        clips = narrate(sc, d)
        tot = sum(c["dur"] for c in clips)
        print(f"  narrated {sum(1 for c in clips if c['dur'] > 0)}/{len(clips)} scenes, "
              f"{tot:.1f}s of voice")
        a = assemble(sc, d, clips)
        print(f"  storyboard   {a['storyboard'].name}  "
              f"{a['storyboard'].stat().st_size/1e3:.0f}KB")
        print(f"  narration    narration.wav  {a['audio_sec']}s  "
              f"{a['audio'].stat().st_size/1e6:.1f}MB  (this is the final track)")
        print(f"  motion       {a['motion'].name}  "
              f"{a['motion'].stat().st_size/1e3:.0f}KB")
        print(f"  mp4          needs ffmpeg - see ffmpeg.txt")
    return 0


