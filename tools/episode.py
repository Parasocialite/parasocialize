        body.append(f'<line x1="{x0}" y1="{y + (len(lines)-1)*lh + 62:.0f}" '
                    f'x2="{x0 + 170}" y2="{y + (len(lines)-1)*lh + 62:.0f}" '
                    f'stroke="{ac}" stroke-width="9"/>')
