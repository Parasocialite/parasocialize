"""
episode.py - turn one encyclopedia entry into one short-form video episode.

THE ARGUMENT
A channel is a format, not a subject. This file is that format.

    HOOK      0-4s    the contradiction. no preamble, no channel name, no
                      "hey guys". one line, large, and it has to be the thing
                      that makes a stranger stop scrolling.
    CARD      4-9s    where and when. year set enormous, because the argument
                      of this whole project is that the same thing has been
                      happening for a very long time.
    BEATS     9-38s   three or four short lines, one idea each, on screen
                      understated so the narration carries them
    WHY       38-50s  the line that makes it matter now. this is the site's
                      own voice, and it is the reason the video is worth making
    END       50-55s  entry N of 175, and where the citation lives

Every entry in the encyclopedia already has a summary and a significance line.
Those are the beats and the why. So the reference work is the script library -
175 episodes exist in draft - and the human job is one line: THE HOOK. The tool
does everything else, which is the only way a channel is sustainable.

WHAT IS NOT IN THESE VIDEOS
No real person is depicted. Not a frame, not a generated likeness, not a
synthetic clip of a creator or a character played by an actor. The brand being
reliable is the entire asset, and it is gone for good the first time a fake clip
of a real person goes out. So the visuals are type, marks and the mascot, and
the subject stays off screen. This is a constraint, and it is also why the whole
thing is buildable in an afternoon.

OUTPUT
    episode/<id>/script.json     the scene list, the narration, the timings
    episode/<id>/scenes/*.png    one frame per scene, rendered in Chrome
    episode/<id>/voice/*.wav     narration, one file per scene
    episode/<id>/<id>.webp       the assembled episode, playable anywhere
    episode/<id>/ffmpeg.txt      the one command for an mp4, for when ffmpeg
                                 is on the machine

  python tools/episode.py eliza                    # build one
  python tools/episode.py --set                    # build the proof set
  python tools/episode.py --list                   # what is drafted
"""
