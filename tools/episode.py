def _offset_delays(css: str, t: float) -> str:
    """Shift every animation-delay by -t so a frame is frozen at instant t.

    Rewriting the delay rather than reaching for Chrome's virtual-time budget
    is the whole trick. --virtual-time-budget on an infinite animation never
    returns - the render hangs until it is killed - whereas a negative delay
    is instant, needs no extra flag, and is exactly reproducible.
    """
    def shift(m):
        return f"animation-delay:{-t + float(m.group(1)):.3f}s"
    return re.sub(r"animation-delay:(-?[\d.]+)s", shift, css)


def _wrap(text, fs, w):
    """Greedy word wrap. Every returned line is guaranteed to measure <= w,
    which is the property the old line-COUNT check was missing."""
    words, lines, cur = str(text).split(), [], []
    cap = max(6, int(w / (fs * 0.47)))
    for wd in words:
        if cur and len(" ".join(cur + [wd])) > cap:
            lines.append(" ".join(cur))
            cur = [wd]
        else:
            cur.append(wd)
    if cur:
        lines.append(" ".join(cur))
    return lines or [""]


def _fit(text, w, sizes, maxlines=4):
    """Largest size at which the text wraps to at most `maxlines` inside `w`.

    Counting lines is not sufficient on its own and was the original bug: a
    short hook came back as "one line", which was then rendered as one line at
    116px and ran straight off the frame. So this returns the wrapped lines and
    every caller draws those, not the raw string.
    """
    for fs in sizes:
        lines = _wrap(text, fs, w)
        if len(lines) <= maxlines:
            return fs, lines
    return sizes[-1], _wrap(text, sizes[-1], w)[:maxlines]


def render_scenes(script: dict, d: pathlib.Path, entry: dict, enc: dict,
                  frames: int = 4) -> list[dict]:
    """Render every scene at `frames` instants of its own animation.

    Four unique frames per scene is the deliberate trade. A full 30fps render is
    1500 Chrome launches - about 25 minutes an episode and 120MB of PNG - and it
    buys nothing, because the motion here is a slow field and the audience
    cannot tell 30fps from 8. ffmpeg's concat demuxer holds each of the four
    frames for its scene's real duration, so the timeline is exact anyway.
    """
    sd = d / "scenes"
    sd.mkdir(parents=True, exist_ok=True)
    out = []
    for i, s in enumerate(script["scenes"]):
        shots = []
        for k in range(frames):
            # spread the samples across the whole loop so a 19s orbit actually
            # shows four different places, not four adjacent ones
            t = (k / frames) * LOOP
            hp = sd / f"{i:02d}_{k}.html"
            hp.write_text(scene_html(s, SAFE, entry, enc, t, i), encoding="utf-8")
            png = sd / f"{i:02d}_{k}.png"
            if png.exists():
                png.unlink()
            url = "file:///" + hp.resolve().as_posix().lstrip("/")
            r = subprocess.run([
                CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                "--no-sandbox", f"--screenshot={png.resolve()}",
                f"--window-size={VW},{VH}",
                f"--user-data-dir={(OUT / '.chrome').resolve()}", url,
            ], check=False, capture_output=True, timeout=180)
            if not png.exists():
                err = r.stderr.decode(errors="replace").strip().splitlines()
                print(f"    scene {i} frame {k} rendered nothing: "
                      f"{err[-1][:110] if err else 'no stderr'}")
            else:
                shots.append(png)
        out.append({"i": i, "shots": shots})
    return out


def concat_manifest(script: dict, d: pathlib.Path, scenes: list[dict],
                    clips: list[dict]) -> pathlib.Path:
    """ffmpeg concat demuxer listing, with each frame held for its real share.

    Durations come from the narration, so the visuals change when the voice
    changes without anyone editing a timing by hand.
    """
    lines = ["# concat demuxer: every motion frame, held for its share of the scene",
             "# paths are relative to THIS file, which is the episode root, so",
             "# they need the scenes/ prefix. ffmpeg resolved bare filenames",
             "# against the episode root too and failed with 'Impossible to",
             "# open 00_0.png' - the storyboard masked it, because the storyboard",
             "# globs the directory directly and never reads the manifest."]
    rel = "scenes/"
    for sc, c in zip(scenes, clips):
        shots = sc["shots"]
        if not shots:
            continue
        per = (c["dur"] or 1.0) / len(shots)
        for j, png in enumerate(shots):
            lines.append(f"file '{rel}{png.name}'")
            lines.append(f"duration {per:.4f}")
    # the concat demuxer ignores the last duration unless the final file is
    # repeated, so it is
    if scenes and scenes[-1]["shots"]:
        lines.append(f"file '{rel}{scenes[-1]['shots'][-1].name}'")
    mf = d / "frames.txt"
    mf.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return mf


# ------------------------------------------------------------------ narration
# SelectVoice('Microsoft David') fails on this machine: the voice is listed by
# GetInstalledVoices but is disabled, and the error only surfaces at speak time,
# after the wave file has already been opened. So pick the first voice that is
# actually enabled instead of naming one.
PS_VOICE = r"""
Add-Type -AssemblyName System.Speech
$s = New-Object System.Speech.Synthesis.SpeechSynthesizer
$v = $s.GetInstalledVoices() | Where-Object {{ $_.Enabled }} | Select-Object -First 1
if ($v) {{ $s.SelectVoice($v.VoiceInfo.Name) }}
$s.Rate = {{0}}
$s.SetOutputToWaveFile('{out}')
$s.Speak('{text}')
$s.Dispose()
"""


def narrate(script: dict, d: pathlib.Path) -> list[dict]:
    vd = d / "voice"
    vd.mkdir(parents=True, exist_ok=True)
    out = []
    for i, s in enumerate(script["scenes"]):
        wav = vd / f"{i:02d}.wav"
        if wav.exists():
            wav.unlink()
        text = (s["say"].replace("'", "''")
                .replace('"', '').replace("dot com", " dot dot com"))
        # the pivot is read slower than a beat: it is a full stop, and the
        # silence after it is part of why it works
        rate = 1 if s["kind"] in ("hook", "why", "pivot") else 0
        ps = d / f"{i:02d}.ps1"
        ps.write_text(PS_VOICE.format(out=str(wav), text=text, rate=rate),
                      encoding="utf-8")
        # -ExecutionPolicy Bypass: the default policy on this machine refuses to
        # run any .ps1 from disk, so every scene came back silent.
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                        "-File", str(ps)],
                       check=False, capture_output=True, timeout=240)
        ps.unlink()
        dur = 0.0
        if wav.exists():
            with wave.open(str(wav), "rb") as w:
                dur = w.getnframes() / float(w.getframerate())
        out.append({"i": i, "wav": str(wav), "dur": round(dur, 2),
                    "kind": s["kind"], "say": s["say"]})
    return out


