# ----------------------------------------------------------------- script gen
def _fmt_year(y):
    if y is None:
        return ""
    return f"{abs(y)} BC" if y < 0 else str(y)


def _sentence_case(s: str) -> str:
    s = re.sub(r"\s+", " ", str(s)).strip()
    return s[:1].upper() + s[1:] if s else s


def build_script(eid: str, enc: dict) -> dict | None:
    d = DRAFTS.get(eid)
    if not d:
        return None
    ent = next((x for x in enc["entries"] if x["id"] == eid), None)
    if not ent:
        return None
    n = next(i for i, x in enumerate(enc["entries"], 1) if x["id"] == eid)

    lane = (ent.get("lanes") or ["application"])[0]
    accent = LANE.get(lane, "#00e8c0")
    year = _fmt_year(ent.get("year"))
    title = ent.get("title", eid)

    scenes = [{
        "kind": "hook", "text": d["hook"], "accent": accent,
        "sub": "", "title": title, "year": year,
    }, {
        "kind": "card", "text": title, "sub": lane.upper(), "accent": accent,
        "year": year, "n": n,
    }]
    for b in d["beats"]:
        scenes.append({"kind": "beat", "text": _sentence_case(b),
                       "accent": accent, "year": year})
    # The retention reset, placed here and not at the end: the second wave of
    # dropoff is at the midpoint, and a payoff that arrives after the room has
    # already gone cannot hold it.
    if d.get("pivot"):
        scenes.append({"kind": "pivot", "text": _sentence_case(d["pivot"]),
                       "accent": accent, "year": year, "title": title})
    scenes.append({"kind": "why", "text": d["why"], "accent": accent,
                   "year": year, "title": title})
    scenes.append({
        "kind": "end", "text": title, "sub": f"ENTRY {n} OF {len(enc['entries'])}",
        "accent": accent, "year": year,
        "url": "parasocialize.com",
    })

    # narration per scene
    for s in scenes:
        if s["kind"] == "card":
            s["say"] = f"{year}. {title}." if year else title
        elif s["kind"] == "end":
            s["say"] = (f"Entry {n} of {len(enc['entries'])}. {title}. "
                        f"Full citation at parasocialize dot com.")
        else:
            s["say"] = s["text"]
    return {"id": eid, "title": title, "year": year, "lane": lane,
            "accent": accent, "n": n, "total": len(enc["entries"]),
            "scenes": scenes}


